SELECT f.id, 'Caixa 1', 'ativo'
FROM filial f
WHERE f.status <> 'deletado';

INSERT INTO usuario_caixa (id_usuario, id_caixa, padrao, status)
SELECT u.id, c.id, CASE WHEN f.principal THEN TRUE ELSE FALSE END, 'ativo'
FROM usuario u
JOIN usuario_filial uf ON uf.id_usuario = u.id AND uf.status <> 'deletado'
JOIN caixa c ON c.id_filial = uf.id_filial AND c.status <> 'deletado'
JOIN filial f ON f.id = c.id_filial
WHERE u.status <> 'deletado';
