UPDATE produto
SET id_modelo = (
    SELECT mo.id FROM modelo mo
    WHERE mo.id_marca = produto.id_marca
      AND mo.tipo = produto.tipo
      AND LOWER(mo.nome) = LOWER(TRIM(produto.nome))
    LIMIT 1
)
WHERE id_modelo IS NULL;

UPDATE produto
SET id_modelo = (
    SELECT mo.id FROM modelo mo
    WHERE mo.id_marca = produto.id_marca AND mo.tipo = produto.tipo
    ORDER BY mo.id
    LIMIT 1
)
WHERE id_modelo IS NULL;

