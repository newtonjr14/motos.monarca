CREATE TABLE marca (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(80) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ativo'
);

INSERT INTO marca (nome, status) VALUES ('Monarca', 'ativo');

CREATE TABLE modelo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_marca BIGINT NOT NULL REFERENCES marca (id),
    nome VARCHAR(120) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ativo'
);

ALTER TABLE produto ADD COLUMN id_marca BIGINT REFERENCES marca (id);
ALTER TABLE produto ADD COLUMN id_modelo BIGINT REFERENCES modelo (id);

INSERT INTO marca (nome, status)
SELECT DISTINCT TRIM(p.marca), 'ativo'
FROM produto p
WHERE p.marca IS NOT NULL AND TRIM(p.marca) <> ''
  AND NOT EXISTS (
      SELECT 1 FROM marca m
      WHERE LOWER(m.nome) = LOWER(TRIM(p.marca))
  );

INSERT INTO modelo (id_marca, nome, tipo, status)
SELECT DISTINCT m.id,
       CASE WHEN LENGTH(TRIM(p.nome)) > 0 THEN TRIM(p.nome) ELSE 'Padrão' END,
       p.tipo,
       'ativo'
FROM produto p
JOIN marca m ON LOWER(m.nome) = LOWER(TRIM(p.marca))
WHERE p.id_modelo IS NULL
  AND p.marca IS NOT NULL
  AND TRIM(p.marca) <> '';

INSERT INTO modelo (id_marca, nome, tipo, status)
SELECT DISTINCT (SELECT id FROM marca WHERE LOWER(nome) = 'monarca' LIMIT 1),
       CASE WHEN LENGTH(TRIM(p.nome)) > 0 THEN TRIM(p.nome) ELSE 'Padrão' END,
       p.tipo,
       'ativo'
FROM produto p
WHERE p.id_modelo IS NULL
  AND (p.marca IS NULL OR TRIM(p.marca) = '');

